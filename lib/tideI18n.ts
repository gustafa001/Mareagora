export type SiteLang = 'pt' | 'en';

/**
 * Detecta o idioma pelo caminho: qualquer rota sob /tide é a versão em inglês;
 * o resto do site é português.
 */
export function useSiteLang(): SiteLang {
  const path = usePathname();
  return path.startsWith('/tide') ? 'en' : 'pt';
}

